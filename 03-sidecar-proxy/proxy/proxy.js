const http = require("http");
const https = require("https");
const tls = require("tls");
const fs = require("fs");
const REAL_API_KEY = process.env.ANTHROPIC_API_KEY;
const REAL_GH_TOKEN = process.env.GH_TOKEN;
const UPSTREAM_HOST = process.env.UPSTREAM_HOST || "api.anthropic.com";
const UPSTREAM_PORT = parseInt(process.env.UPSTREAM_PORT || "443");
const LISTEN_PORT = parseInt(process.env.LISTEN_PORT || "8080");
const CERT_DIR = process.env.CERT_DIR || "/app/certs";

if (!REAL_API_KEY) {
  console.error("Error: ANTHROPIC_API_KEY not set in proxy sidecar");
  process.exit(1);
}

// Load MITM certs (generated by entrypoint.sh)
let mitmKey, mitmCert;
try {
  mitmKey = fs.readFileSync(`${CERT_DIR}/server-key.pem`);
  mitmCert = fs.readFileSync(`${CERT_DIR}/server-cert.pem`);
} catch (e) {
  console.warn("MITM certs not found — CONNECT proxy disabled (Anthropic-only mode)");
}

// Allowed hosts for CONNECT MITM
const GITHUB_HOSTS = new Set(["github.com", "api.github.com"]);

// Internal HTTP server to handle decrypted MITM traffic
const mitmHandler = (req, res, targetHost) => {
  const headers = { ...req.headers };

  // Replace Authorization header with real GitHub token
  if (REAL_GH_TOKEN && headers["authorization"]) {
    const auth = headers["authorization"];
    if (auth.startsWith("token ")) {
      headers["authorization"] = `token ${REAL_GH_TOKEN}`;
    } else if (auth.startsWith("Basic ")) {
      // Decode base64, replace password, re-encode
      const decoded = Buffer.from(auth.slice(6), "base64").toString();
      const colonIdx = decoded.indexOf(":");
      if (colonIdx !== -1) {
        const username = decoded.slice(0, colonIdx);
        const encoded = Buffer.from(`${username}:${REAL_GH_TOKEN}`).toString("base64");
        headers["authorization"] = `Basic ${encoded}`;
      }
    }
  }

  headers["host"] = targetHost;

  const options = {
    hostname: targetHost,
    port: 443,
    path: req.url,
    method: req.method,
    headers: headers,
  };

  const proxyReq = https.request(options, (proxyRes) => {
    res.writeHead(proxyRes.statusCode, proxyRes.headers);
    proxyRes.pipe(res);
  });

  proxyReq.on("error", (err) => {
    console.error(`MITM proxy error (${targetHost}): ${err.message}`);
    res.writeHead(502);
    res.end("Bad Gateway");
  });

  req.pipe(proxyReq);
};

// Main HTTP server handles plain HTTP requests (Anthropic SDK)
const server = http.createServer((req, res) => {
  const headers = { ...req.headers };

  // Replace the API key header with the real one
  headers["x-api-key"] = REAL_API_KEY;
  headers["host"] = UPSTREAM_HOST;

  const options = {
    hostname: UPSTREAM_HOST,
    port: UPSTREAM_PORT,
    path: req.url,
    method: req.method,
    headers: headers,
  };

  const proxyReq = https.request(options, (proxyRes) => {
    res.writeHead(proxyRes.statusCode, proxyRes.headers);
    proxyRes.pipe(res);
  });

  proxyReq.on("error", (err) => {
    console.error(`Proxy error: ${err.message}`);
    res.writeHead(502);
    res.end("Bad Gateway");
  });

  req.pipe(proxyReq);
});

// CONNECT handler for HTTPS_PROXY requests (gh CLI, git)
server.on("connect", (req, clientSocket, head) => {
  const [host, portStr] = req.url.split(":");
  const port = parseInt(portStr || "443");

  // Only allow MITM for GitHub hosts
  if (!GITHUB_HOSTS.has(host)) {
    console.log(`CONNECT rejected: ${host}:${port} (not in allowlist)`);
    clientSocket.write("HTTP/1.1 403 Forbidden\r\n\r\n");
    clientSocket.destroy();
    return;
  }

  if (!mitmKey || !mitmCert) {
    console.error(`CONNECT to ${host}:${port} but MITM certs not available`);
    clientSocket.write("HTTP/1.1 502 Bad Gateway\r\n\r\n");
    clientSocket.destroy();
    return;
  }

  // Tell client the tunnel is established
  clientSocket.write("HTTP/1.1 200 Connection Established\r\n\r\n");

  // Wrap client socket with TLS (MITM — we are the server)
  const tlsSocket = new tls.TLSSocket(clientSocket, {
    isServer: true,
    key: mitmKey,
    cert: mitmCert,
  });

  // Create a per-connection HTTP server to parse the decrypted traffic
  const innerServer = new http.Server();
  innerServer.on("request", (innerReq, innerRes) => {
    mitmHandler(innerReq, innerRes, host);
  });

  // Feed the TLS socket to the inner HTTP server
  innerServer.emit("connection", tlsSocket);

  if (head && head.length > 0) {
    tlsSocket.unshift(head);
  }

  tlsSocket.on("error", (err) => {
    if (err.code !== "ECONNRESET") {
      console.error(`TLS error (${host}): ${err.message}`);
    }
  });

  clientSocket.on("error", (err) => {
    if (err.code !== "ECONNRESET") {
      console.error(`Client socket error (${host}): ${err.message}`);
    }
  });
});

// Listen on all interfaces (IPv4 + IPv6) within the pod's shared network namespace
server.listen(LISTEN_PORT, () => {
  console.log(`Credential proxy listening on port ${LISTEN_PORT}`);
  console.log(`Forwarding Anthropic API to ${UPSTREAM_HOST}:${UPSTREAM_PORT}`);
  if (mitmKey && REAL_GH_TOKEN) {
    console.log(`MITM proxy enabled for: ${[...GITHUB_HOSTS].join(", ")}`);
  } else if (!REAL_GH_TOKEN) {
    console.log("GH_TOKEN not set — GitHub MITM disabled");
  }
});
